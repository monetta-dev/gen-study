from pathlib import Path
import unittest


class ViewerTests(unittest.TestCase):
    def test_viewer_static_files_include_latex_rendering_hooks(self):
        root = Path(__file__).resolve().parents[1]
        html = (root / "viewer" / "index.html").read_text(encoding="utf-8")
        script = (root / "viewer" / "app.js").read_text(encoding="utf-8")
        config = (root / "viewer" / "config.js").read_text(encoding="utf-8")
        styles = (root / "viewer" / "styles.css").read_text(encoding="utf-8")

        self.assertIn("MathJax", html)
        self.assertIn("tex-svg.js", html)
        # MathJax is configured to suppress TeX parse errors (noerrors) and
        # to pre-load the mhchem/physics/boldsymbol extensions so that \ce,
        # \pu, \boldsymbol, and physics-package macros render instead of
        # producing "Math input error". processEscapes is set so \$ is a
        # literal dollar, not a math delimiter.
        self.assertIn("noerrors", html)
        self.assertIn("mhchem", html)
        self.assertIn("physics", html)
        self.assertIn("boldsymbol", html)
        self.assertIn("processEscapes", html)
        self.assertIn("./config.js", html)
        self.assertIn("generateForm", html)
        self.assertIn("subjectInput", html)
        self.assertIn("levelInput", html)
        self.assertIn("topicInput", html)
        self.assertIn("apiKeyInput", html)
        self.assertIn("visualApiUrlInput", html)
        self.assertIn("autoVisualInput", html)
        self.assertIn("problemOutput", html)
        self.assertIn("solutionOutput", html)
        self.assertIn("copyProblemButton", html)
        self.assertIn("copySolutionButton", html)
        self.assertIn("copy-button", html)
        self.assertIn("section-header", html)
        self.assertIn("visualOutput", html)
        self.assertIn("processOutput", html)
        self.assertIn("Plain Text", html)
        self.assertIn("window.GEN_STUDY_CONFIG", config)
        self.assertIn("visualApiUrl", config)
        self.assertIn("includeTrace", config)
        self.assertIn("showProcess", config)
        self.assertIn("showFullRawResponse", config)
        self.assertIn("GEN_STUDY_CONFIG", script)
        self.assertIn("configFlag", script)
        self.assertIn("defaultTopicsBySubject", script)
        self.assertIn("initializeRequestDefaults", script)
        self.assertIn("syncTopicForSubject", script)
        self.assertIn("defaultVisualApiUrl", script)
        self.assertIn("fetchJsonResult", script)
        self.assertIn("generateVisuals", script)
        self.assertIn("renderVisualResponse", script)
        self.assertIn("png_base64", script)
        self.assertIn("visual-image", script)
        self.assertIn("compile_transcript", script)
        self.assertIn("tikz_source", script)
        self.assertIn("renderTraceRecords", script)
        self.assertIn("redactRawResponse", script)
        self.assertIn("plainTextResponse", script)
        self.assertIn("base64 omitted", script)
        self.assertIn("png_base64", script)
        self.assertIn("includeTrace", script)
        self.assertIn("visual_assets", script)
        self.assertIn("normalizeTextLatex", script)
        self.assertIn("copyTextToClipboard", script)
        self.assertIn("navigator.clipboard", script)
        self.assertIn("execCommand", script)
        self.assertIn("Copied!", script)
        self.assertIn("syncCopyButtons", script)
        self.assertIn("copySectionText", script)
        self.assertIn("appendRichText", script)
        self.assertIn("enumerate", script)
        self.assertIn("textbf", script)
        # The inline $...$ math regex uses a negative lookbehind so escaped
        # dollars (\$) are not treated as math delimiters, and nested
        # \textbf/\emph braces are balanced by findMatchingBrace.
        self.assertIn("lookbehind", script)
        self.assertIn("findMatchingBrace", script)
        self.assertIn("fetch(apiUrl", script)
        self.assertIn("formatNonJsonResponse", script)
        self.assertIn("probably reached an HTML page", script)
        self.assertIn("typesetPromise", script)
        self.assertIn(".generation-form", styles)
        self.assertIn(".latex-list", styles)
        self.assertIn(".rendered-text", styles)
        # Broken TeX is rendered by MathJax's noerrors extension as an SVG
        # carrying a data-mjx-error attribute; highlight it so the failed
        # expression is visible rather than silently malformed.
        self.assertIn("[data-mjx-error]", styles)
        self.assertIn(".visual-grid", styles)
        self.assertIn(".visual-figure", styles)
        self.assertIn(".visual-image", styles)
        self.assertIn(".tikz-source", styles)
        self.assertIn(".process-group", styles)
        self.assertIn(".process-item", styles)
        self.assertIn(".copy-button", styles)
        self.assertIn(".section-header", styles)
        self.assertIn(".status.loading", styles)
        self.assertIn("@keyframes spin", styles)
